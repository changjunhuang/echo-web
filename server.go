// Message represents a chat message
type Message struct {
	Role    string `json:"role"`
	Content string `json:"content"`
}

// ChatRequest represents the incoming chat request
type ChatRequest struct {
	Model     string    `json:"model"`
	UserID    string    `json:"userId"`
	SessionID string    `json:"sessionId"`
	Message   string    `json:"message"`
	Stream    bool      `json:"stream"`
	Messages  []Message `json:"messages"`
}

// Session stores conversation history for a session
type Session struct {
	ID        string
	UserID    string
	Messages  []Message
	CreatedAt time.Time
	UpdatedAt time.Time
	mu        sync.RWMutex
}

var (
	sessions = make(map[string]*Session)
	smu      sync.RWMutex
)

// getOrCreateSession gets or creates a session
func getOrCreateSession(userID, sessionID string) *Session {
	smu.Lock()
	defer smu.Unlock()

	key := userID + ":" + sessionID
	if session, exists := sessions[key]; exists {
		session.UpdatedAt = time.Now()
		return session
	}

	session := &Session{
		ID:        sessionID,
		UserID:    userID,
		Messages:  make([]Message, 0),
		CreatedAt: time.Now(),
		UpdatedAt: time.Now(),
	}
	sessions[key] = session
	return session
}

// generateResponse generates a simple AI response
func generateResponse(session *Session, userMessage string) string {
	session.mu.Lock()
	defer session.mu.Unlock()

	session.Messages = append(session.Messages, Message{
		Role:    "user",
		Content: userMessage,
	})

	response := generateContextualResponse(userMessage)

	session.Messages = append(session.Messages, Message{
		Role:    "assistant",
		Content: response,
	})

	return response
}

func generateContextualResponse(message string) string {
	msg := strings.ToLower(message)

	if strings.Contains(msg, "hello") || strings.Contains(msg, "hi") {
		return "Hello! I'm your AI assistant. How can I help you today?"
	}
	if strings.Contains(msg, "how are you") {
		return "I'm doing great, thank you for asking! I'm here to help you with any questions you might have."
	}
	if strings.Contains(msg, "bye") || strings.Contains(msg, "goodbye") {
		return "Goodbye! Feel free to come back anytime you need assistance. Have a great day!"
	}
	if strings.Contains(msg, "thank") {
		return "You're welcome! Is there anything else I can help you with?"
	}
	if strings.Contains(msg, "help") {
		return "I can help you with a variety of tasks including:\n- Answering questions\n- Writing code\n- Explaining concepts\n- Brainstorming ideas\n- And much more!\n\nWhat would you like to know?"
	}

	return fmt.Sprintf("I received your message: \"%s\"\n\nThis is a demo response. In production, this would be generated by an AI model. The chat interface supports userId and sessionId for maintaining conversation context across sessions.", message)
}

func chatHandler(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		http.Error(w, "Method not allowed", http.StatusMethodNotAllowed)
		return
	}

	var req ChatRequest
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		http.Error(w, "Invalid request body", http.StatusBadRequest)
		return
	}

	session := getOrCreateSession(req.UserID, req.SessionID)
	response := generateResponse(session, req.Message)

	w.Header().Set("Content-Type", "text/event-stream")
	w.Header().Set("Cache-Control", "no-cache")
	w.Header().Set("Connection", "keep-alive")
	w.Header().Set("X-Accel-Buffering", "no")
	flusher, ok := w.(http.Flusher)
	if !ok {
		http.Error(w, "Streaming unsupported", http.StatusInternalServerError)
		return
	}

	// 按 OpenAI 风格发送增量帧：data: {"choices":[{"delta":{"content":"<char>"}}]}\n\n
	// 这样前端可以无差别地复用 OpenAI 兼容的 SSE 解析器
	for _, ch := range chunksOfString(response) {
		frame := map[string]interface{}{
			"choices": []map[string]interface{}{
				{"delta": map[string]string{"content": ch}},
			},
		}
		data, err := json.Marshal(frame)
		if err != nil {
			log.Printf("[chat] marshal frame failed: %v", err)
			continue
		}
		fmt.Fprintf(w, "data: %s\n\n", data)
		flusher.Flush()
		time.Sleep(20 * time.Millisecond)
	}

	// 终止帧：data: [DONE]\n\n
	fmt.Fprintf(w, "data: [DONE]\n\n")
	flusher.Flush()
	log.Printf("[chat] stream done sessionId=%s", req.SessionID)
}

// chunksOfString 将字符串切成字符切片，按 UTF-8 rune 切，避免把多字节字符拆坏
func chunksOfString(s string) []string {
	out := make([]string, 0, len(s))
	for _, r := range s {
		out = append(out, string(r))
	}
	return out
}

func completionsHandler(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		http.Error(w, "Method not allowed", http.StatusMethodNotAllowed)
		return
	}

	var req ChatRequest
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		http.Error(w, "Invalid request body", http.StatusBadRequest)
		return
	}

	session := getOrCreateSession(req.UserID, req.SessionID)
	response := generateResponse(session, req.Message)

	resp := map[string]interface{}{
		"id": fmt.Sprintf("chatcmpl-%d", time.Now().UnixNano()),
		"choices": []map[string]interface{}{
			{
				"message": map[string]string{
					"role":    "assistant",
					"content": response,
				},
				"finish_reason": "stop",
			},
		},
		"usage": map[string]int{
			"prompt_tokens":     10,
			"completion_tokens": len(response) / 4,
			"total_tokens":      10 + len(response)/4,
		},
	}

	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(resp)
}

func ipHandler(w http.ResponseWriter, r *http.Request) {
	ip := r.Header.Get("X-Forwarded-For")
	if ip == "" {
		ip = r.Header.Get("X-Real-IP")
	}
	if ip == "" {
		addr := r.RemoteAddr
		if strings.HasPrefix(addr, "[") {
			parts := strings.Split(addr, "]")
			if len(parts) > 0 {
				ip = strings.TrimPrefix(parts[0], "[")
			}
		} else {
			ip = strings.Split(addr, ":")[0]
		}
	}

	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(map[string]string{"ip": ip})
}

