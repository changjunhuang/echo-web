// User 内存中的账号信息（密码以 SHA-256 摘要存储）
type User struct {
	ID         int64     `json:"id"`
	Username   string    `json:"username"`
	Password   string    `json:"-"` // 摘要，不返回给前端
	Nickname   string    `json:"nickname"`
	Phone      string    `json:"phone"`
	Email      string    `json:"email"`
	Role       string    `json:"role"`     // user / admin
	Avatar     string    `json:"avatar"`   // emoji 或 URL
	Bio        string    `json:"bio"`      // 个性签名
	Gender     string    `json:"gender"`   // male / female / other
	Birthday   string    `json:"birthday"` // YYYY-MM-DD
	CreatedAt  time.Time `json:"createdAt"`
}

// AuthSession 登录会话
type AuthSession struct {
	SessionID string
	UserID    int64
	ExpiresAt time.Time
}

const (
	sessionTTL  = 1 * time.Hour
	passwordSalt = "echo-web-salt"
)

var (
	authMu       sync.RWMutex
	users        = make(map[string]*User)         // key: username
	usersByID    = make(map[int64]*User)          // key: id
	authSessions = make(map[string]*AuthSession)  // key: sessionId
	nextUserID   int64 = 1
)

// jsonResp 统一响应封装
func jsonResp(w http.ResponseWriter, status int, code int, message string, data interface{}) {
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(status)
	json.NewEncoder(w).Encode(map[string]interface{}{
		"code":    code,
		"message": message,
		"data":    data,
	})
}

// jsonOK 成功响应
func jsonOK(w http.ResponseWriter, data interface{}) {
	jsonResp(w, http.StatusOK, 0, "ok", data)
}

// jsonErr 业务错误
func jsonErr(w http.ResponseWriter, status, code int, message string) {
	jsonResp(w, status, code, message, nil)
}

// hashPassword 计算密码摘要
func hashPassword(password string) string {
	h := sha256.Sum256([]byte(password + passwordSalt))
	return hex.EncodeToString(h[:])
}

// randomID 生成随机 sessionId
func randomID() string {
	b := make([]byte, 24)
	rand.Read(b)
	return base64.RawURLEncoding.EncodeToString(b)
}

// sweepSessions 清理过期会话（仅惰性触发）
func sweepSessions() {
	now := time.Now()
	for k, v := range authSessions {
		if now.After(v.ExpiresAt) {
			delete(authSessions, k)
		}
	}
}

// loginRequest 登录入参
type loginRequest struct {
	Username    string `json:"username"`
	Password    string `json:"password"`
}

// loginHandler POST /api/auth/login
func loginHandler(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		jsonErr(w, http.StatusMethodNotAllowed, 405, "Method not allowed")
		return
	}

	var req loginRequest
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		jsonErr(w, http.StatusBadRequest, 400, "请求体格式错误")
		return
	}
	req.Username = strings.TrimSpace(req.Username)
	if req.Username == "" || req.Password == "" {
		jsonErr(w, http.StatusBadRequest, 400, "账号和密码不能为空")
		return
	}

	authMu.Lock()
	defer authMu.Unlock()

	// 校验账号密码
	u, exists := users[req.Username]
	if !exists || u.Password != hashPassword(req.Password) {
		jsonErr(w, http.StatusUnauthorized, 401, "账号或密码错误")
		return
	}

	// 创建会话
	sweepSessions()
	sessionID := randomID()
	authSessions[sessionID] = &AuthSession{
		SessionID: sessionID,
		UserID:    u.ID,
		ExpiresAt: time.Now().Add(sessionTTL),
	}

	log.Printf("[auth] login success username=%s sessionId=%s", u.Username, sessionID)
	jsonOK(w, map[string]interface{}{
		"sessionId":  sessionID,
		"expiresAt":  time.Now().Add(sessionTTL).Unix(),
		"expiresIn":  int(sessionTTL.Seconds()),
		"user": map[string]interface{}{
			"id":       u.ID,
			"username": u.Username,
			"nickname": u.Nickname,
			"phone":    u.Phone,
			"email":    u.Email,
			"role":     u.Role,
			"avatar":   u.Avatar,
			"bio":      u.Bio,
			"gender":   u.Gender,
			"birthday": u.Birthday,
		},
	})
}

// registerRequest 注册入参
type registerRequest struct {
	Username   string `json:"username"`
	Password   string `json:"password"`
	Nickname   string `json:"nickname"`
	Phone      string `json:"phone"`
	Email      string `json:"email"`
	Avatar     string `json:"avatar"`
	Bio        string `json:"bio"`
	Gender     string `json:"gender"`
	Birthday   string `json:"birthday"`
}

// registerHandler POST /api/auth/register
func registerHandler(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		jsonErr(w, http.StatusMethodNotAllowed, 405, "Method not allowed")
		return
	}

	var req registerRequest
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		jsonErr(w, http.StatusBadRequest, 400, "请求体格式错误")
		return
	}
	req.Username = strings.TrimSpace(req.Username)
	req.Nickname = strings.TrimSpace(req.Nickname)
	req.Phone = strings.TrimSpace(req.Phone)
	req.Email = strings.TrimSpace(req.Email)

	if len(req.Username) < 3 {
		jsonErr(w, http.StatusBadRequest, 400, "账号至少 3 个字符")
		return
	}
	if len(req.Password) < 6 {
		jsonErr(w, http.StatusBadRequest, 400, "密码至少 6 位")
		return
	}
	if req.Nickname == "" {
		req.Nickname = req.Username
	}

	authMu.Lock()
	defer authMu.Unlock()

	// 账号唯一
	if _, exists := users[req.Username]; exists {
		jsonErr(w, http.StatusBadRequest, 400, "该账号已被注册")
		return
	}

	u := &User{
		ID:        nextUserID,
		Username:  req.Username,
		Password:  hashPassword(req.Password),
		Nickname:  req.Nickname,
		Phone:     req.Phone,
		Email:     req.Email,
		Role:      "user",
		Avatar:    req.Avatar,
		Bio:       req.Bio,
		Gender:    req.Gender,
		Birthday:  req.Birthday,
		CreatedAt: time.Now(),
	}
	users[u.Username] = u
	usersByID[u.ID] = u
	nextUserID++

	log.Printf("[auth] register success username=%s id=%d", u.Username, u.ID)
	jsonOK(w, map[string]interface{}{
		"id":       u.ID,
		"username": u.Username,
		"nickname": u.Nickname,
	})
}

// checkRequest 会话校验
type checkRequest struct {
	SessionID string `json:"sessionId"`
}

// checkHandler POST /api/auth/check
func checkHandler(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		jsonErr(w, http.StatusMethodNotAllowed, 405, "Method not allowed")
		return
	}

	var req checkRequest
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		jsonErr(w, http.StatusBadRequest, 400, "请求体格式错误")
		return
	}
	if req.SessionID == "" {
		jsonErr(w, http.StatusBadRequest, 400, "缺少 sessionId")
		return
	}

	authMu.RLock()
	sess, ok := authSessions[req.SessionID]
	if !ok || time.Now().After(sess.ExpiresAt) {
		authMu.RUnlock()
		jsonErr(w, http.StatusUnauthorized, 401, "会话已失效，请重新登录")
		return
	}
	u := usersByID[sess.UserID]
	authMu.RUnlock()

	if u == nil {
		jsonErr(w, http.StatusUnauthorized, 401, "账号不存在")
		return
	}
	jsonOK(w, map[string]interface{}{
		"user": map[string]interface{}{
			"id":       u.ID,
			"username": u.Username,
			"nickname": u.Nickname,
			"phone":    u.Phone,
			"email":    u.Email,
			"role":     u.Role,
			"avatar":   u.Avatar,
			"bio":      u.Bio,
			"gender":   u.Gender,
			"birthday": u.Birthday,
		},
		"expiresAt": sess.ExpiresAt.Unix(),
	})
}

// logoutRequest 登出入参
type logoutRequest struct {
	SessionID string `json:"sessionId"`
}

// logoutHandler POST /api/auth/logout
func logoutHandler(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		jsonErr(w, http.StatusMethodNotAllowed, 405, "Method not allowed")
		return
	}
	var req logoutRequest
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		jsonErr(w, http.StatusBadRequest, 400, "请求体格式错误")
		return
	}
	authMu.Lock()
	delete(authSessions, req.SessionID)
	authMu.Unlock()
	log.Printf("[auth] logout sessionId=%s", req.SessionID)
	jsonOK(w, map[string]interface{}{"ok": true})
}

// corsMiddleware 允许跨域（前后端分离开发场景）
func corsMiddleware(next http.HandlerFunc) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Access-Control-Allow-Origin", "*")
		w.Header().Set("Access-Control-Allow-Methods", "GET, POST, PUT, DELETE, OPTIONS")
		w.Header().Set("Access-Control-Allow-Headers", "Content-Type, Authorization, X-Session-Id")
		if r.Method == http.MethodOptions {
			w.WriteHeader(http.StatusNoContent)
			return
		}
		next(w, r)
	}
}

// corsWrap 对 handler 套 CORS
func corsWrap(h http.HandlerFunc) http.HandlerFunc {
	return corsMiddleware(h)
}

